--==============================================================================
-- V7__create_game_highscores.sql
-- Per-user best scores for the games (currently the Breakout easter egg).
-- One row per user and game; the community high score is derived from these
-- rows (highest score, earliest achievement on a tie), so there is no second
-- mutable "leaderboard" record that could drift from the personal bests.
--
-- No foreign key to users: the shared demo user and legacy accounts may own a
-- score without (or before) a user row, and dropping an account must never
-- remove game history. `game` is deliberately a plain text key, not an enum,
-- so future games need no migration.
--==============================================================================

CREATE TABLE game_highscores (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id     VARCHAR(32) NOT NULL,
    game        VARCHAR(32) NOT NULL,
    score       BIGINT NOT NULL,
    achieved_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    city        VARCHAR(128),
    CONSTRAINT game_highscores_pk PRIMARY KEY (id),
    CONSTRAINT game_highscores_user_game_uq UNIQUE (user_id, game)
);

CREATE INDEX idx_game_highscores_game_score
    ON game_highscores (game, score);
